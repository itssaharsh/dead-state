async function runPaste(prose) {
  if (!prose) { say('Nothing to check.'); return; }
  const v = $('#v-path');
  const note = el('p', 'steps', 'Typing content…'); v.append(note);
  say('Typing content.');
  try {
    const r = await fetch('/api/extract', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ prose }) });
    const j = await r.json();
    if (!j.ok) {
      note.remove();
      const e = el('p', 'err');
      e.textContent = j.reason === 'no-provider'
        ? 'No model key is configured on the server, so pasted content cannot be typed. The three samples are pre-typed and their checks still run.'
        : `Couldn't type this content. ${(j.errors || []).slice(0, 3).join('; ')} Nothing was guessed.`;
      v.append(e); say('Could not type this content.');
      return;
    }
    note.remove();
    cur = { title: 'Your content', provenance: {}, quests: [{ slug: 'yours', title: 'Your content', prose }], model: j.model };
    pasted = { provider: j.provider, model: j.model_id };
    gateNow();
  } catch (e) { note.remove(); v.append(Object.assign(el('p', 'err'), { textContent: 'The typing service did not respond. The samples still work offline.' })); }
}

/* ---------------- live gating in a worker ---------------- */
function gateNow() {
  if (!cur?.model?.actions?.length) { say('Nothing to check.'); return; }
  const mine = ++token;                      // any later load invalidates this run
  renderAll(true);
  const prog = el('p', 'steps'); $('#checks').after(prog);
  worker?.terminate();
  worker = new Worker('/worker.js', { type: 'module' });
  worker.onmessage = e => {
    if (mine !== token) return;              // content changed mid-run; drop the result
    const d = e.data;
    if (d.phase === 'step') { prog.textContent = `Checking ${d.n}/${d.of} — ${d.name}`; say(`Check ${d.n} of ${d.of}: ${d.name}`); }
    if (d.phase === 'done') {
      prog.remove(); live = d.result; renderAll(false);
      say(live.softlock.ok && live.world.ok ? 'All three checks passed.'
        : `${live.softlock.traps.length || 0} quests can be permanently blocked. Checked in ${live.ms} milliseconds.`);
    }
  };
  worker.onerror = () => { if (mine !== token) return; prog.remove(); live = null; renderAll(false); say('The check worker failed; showing the recorded run.'); };
  worker.postMessage({ model: cur.model });
}

