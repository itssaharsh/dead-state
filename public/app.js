/* ---------------- data ---------------- */
async function load(pick) {
  token++; worker?.terminate(); worker = null;   // cancel anything in flight
  document.querySelectorAll('.steps').forEach(n => n.remove());
  if (pick === 'paste') return showPaste();
  const f = PICKS[pick]; if (!f) return;
  const mine = token;
  const res = await fetch(f.file); const data = await res.json();
  if (mine !== token) return;                    // a newer pick won
  cur = data; live = null; pasted = null;
  if (!cur.quests) cur.quests = [{ slug: cur.slug, title: cur.title, prose: cur.prose || '' }];
  renderAll(false);
  tab('t-path');
  say(`${f.label} loaded. ${result()?.softlock?.ok ? 'No softlock found.' : (result()?.softlock?.traps?.length || 0) + ' quests can be permanently blocked.'}`);
}

