function renderBand() {
  const r = result(), band = $('#band');
  const blocked = r && (!r.softlock.ok || !r.world.ok);
  band.classList.toggle('blocked', !!blocked);
  const nQuests = cur.quests?.length || 1;
  $('#content-h').textContent = blocked
    ? (!r.world.ok ? 'This content cannot be finished.' : `${r.softlock.traps.length} of ${cur.model.goals.length} quests can be permanently blocked by ordinary play.`)
    : 'A completion order exists, and no ordering blocks it.';
  $('#band-sub').textContent = cur.title + (nQuests > 1 ? ` · ${nQuests} quest lines generated independently, merged into one world` : '');
  const p = cur.provenance || {}, g = cur.generated || {};
  let src;
  if (p.generator === 'none — written by hand') src = 'Hand-written by the author, not generated — it exercises a shape the generated samples did not produce';
  else if (p.generator) src = `Generated by ${p.generator}${p.generated_at ? ', ' + p.generated_at.slice(0, 10) : ''}`;
  else if (g.provider) src = `Generated by ${g.provider}/${g.model}${g.at ? ', ' + g.at.slice(0, 10) : ''}`;
  else src = 'Pasted by you';
  $('#band-src').textContent = src;
}

function renderPath() {
  const v = $('#v-path'); v.replaceChildren();
  const r = result();
  if (!r) return;

  if (!r.softlock.ok && r.softlock.traps.length) {
    const trap = r.softlock.traps[0];
    v.append(el('h3', null, 'A player reaches the trap like this'));
    $('#v-path').lastChild.style.cssText = 'font:500 12px/1 var(--ff-body);letter-spacing:.09em;text-transform:uppercase;color:var(--ink-muted);margin-bottom:12px';
    const ol = el('ul', 'path');
    trap.path.forEach(id => {
      const a = cur.model.actions.find(x => x.id === id);
      const li = el('li');
      const txt = el('span');
      const m = /^\[(\w+)\]\s*(.*)$/.exec(a?.label || id);
      if (m) { const q = el('span', 'q', m[1]); txt.append(q, document.createTextNode(m[2])); }
      else txt.textContent = a?.label || id;
      if (id === trap.by) {
        li.className = 'consumes';
        txt.querySelector('.q')?.after(Object.assign(el('span', 'what'), { textContent: m ? m[2] : (a?.label || id) }));
        if (m) txt.childNodes.forEach(n => { if (n.nodeType === 3) n.remove(); });
        txt.append(el('span', 'note', `↳ this consumes ${trap.blocked.join(' and ')} — and a quest step cannot be repeated`));
      }
      li.append(txt); ol.append(li);
    });
    v.append(ol);

    const dead = el('div', 'dead');
    dead.append(el('h3', null, 'Can never be completed after that'));
    const ul = el('ul');
    for (const t of r.softlock.traps) {
      const li = el('li');
      li.append(el('span', 'x', '✗'));
      const wrap = el('div');
      wrap.append(el('span', 'goal', t.goalLabel.replace(/^\[\w+\]\s*/, '')));
      wrap.append(el('span', 'because', `needs ${t.blocked.join(' and ')}, which nothing can set again`));
      li.append(wrap); ul.append(li);
    }
    dead.append(ul); v.append(dead);
    return;
  }

  if (!r.world.ok) {
    v.append(el('h3', null, 'No completion path exists'));
    v.lastChild.style.cssText = 'font:500 12px/1 var(--ff-body);letter-spacing:.09em;text-transform:uppercase;color:var(--ink-muted);margin-bottom:12px';
    const q = cur.quests?.[0];
    if (q) { const ol = el('ol'); q.prose.split('\n').filter(Boolean).forEach(line => ol.append(el('li', null, line.replace(/^\d+\.\s*/, '')))); 
      const w = el('div', 'quest'); w.append(ol); v.append(w); }
    return;
  }

  v.append(el('h3', null, 'A completion order the search found'));
  v.lastChild.style.cssText = 'font:500 12px/1 var(--ff-body);letter-spacing:.09em;text-transform:uppercase;color:var(--ink-muted);margin-bottom:12px';
  const ol = el('ul', 'path');
  (r.world.order || []).forEach(id => {
    const a = cur.model.actions.find(x => x.id === id);
    ol.append(el('li', null, (a?.label || id)));
  });
  v.append(ol);
  v.append(Object.assign(el('p', 'hint'), { textContent: 'Every other ordering the search reached also leaves every quest completable.' }));
}

function renderQuests() {
  const v = $('#v-quests'); v.replaceChildren();
  const r = result();
  const doomed = new Set((r?.softlock?.traps || []).map(t => (/^\[(\w+)\]/.exec(t.goalLabel) || [])[1]));
  const noPath = r && !r.world.ok;
  if (cur.bible) {
    const d = el('details'); d.append(el('summary', null, 'Shared world bible given to every quest'));
    const pre = el('pre'); pre.style.cssText = 'font:400 12px/1.5 var(--ff-mono);color:var(--ink-muted);white-space:pre-wrap;margin:10px 0 0';
    pre.textContent = cur.bible; d.append(pre);
    d.style.marginBottom = '14px'; v.append(d);
  }
  (cur.quests || []).forEach(q => {
    const w = el('div', 'quest' + (doomed.has(q.slug) || noPath ? ' doomed' : ''));
    w.append(el('h3', null, q.title));
    const label = noPath ? 'no completion path exists in the extracted model'
      : doomed.has(q.slug) ? 'this quest can be permanently blocked'
      : 'completable in every ordering reached';
    if (q.slug) w.append(Object.assign(el('p', 'brief'), { textContent: label }));
    const ol = el('ol');
    q.prose.split('\n').filter(Boolean).forEach(line => ol.append(el('li', null, line.replace(/^\d+\.\s*/, ''))));
    w.append(ol); v.append(w);
  });
}

function renderModel() {
  const v = $('#v-model'); v.replaceChildren();
  const facts = el('div', 'facts');
  Object.entries(cur.model.facts).forEach(([k, val]) =>
    facts.append(el('span', 'chip' + (val ? ' t' : ''), `${k} = ${val}`)));
  v.append(Object.assign(el('h3', null, `${Object.keys(cur.model.facts).length} world facts typed from the prose`)), facts);
  v.firstChild.style.cssText = 'font:500 12px/1 var(--ff-body);letter-spacing:.09em;text-transform:uppercase;color:var(--ink-muted);margin-bottom:10px';
  const tbl = el('table', 'model-tbl');
  tbl.innerHTML = '<thead><tr><th>Step</th><th>Requires</th><th>Changes</th><th>From the text</th></tr></thead>';
  const tb = el('tbody');
  cur.model.actions.forEach(a => {
    const tr = el('tr');
    tr.append(el('td', null, a.label));
    const pre = el('td'), post = el('td');
    const pr = Object.entries(a.pre || {}); const po = Object.entries(a.post || {});
    pre.append(...(pr.length ? pr.map(([k, val]) => Object.assign(el('div', 'pred' + (val ? '' : ' neg')), { textContent: (val ? '' : 'not ') + k })) : [el('div', 'pred', '—')]));
    post.append(...(po.length ? po.map(([k, val]) => Object.assign(el('div', 'pred' + (val ? '' : ' neg')), { textContent: (val ? '' : 'not ') + k })) : [el('div', 'pred', '—')]));
    tr.append(pre, post, Object.assign(el('td', 'quote'), { textContent: a.quote ? `“${a.quote}”` : '—' }));
    tb.append(tr);
  });
  tbl.append(tb); v.append(tbl);
  v.append(Object.assign(el('p', 'hint'), { textContent: 'This is the whole input to the search. If a row is typed wrong, the verdict is wrong — which is why it is shown.' }));
}

function renderChecks(pending) {
  const r = result(), box = $('#checks'); box.replaceChildren();
  const lead = el('p', 'lead');
  lead.textContent = 'The first two checks pass on content that is still broken. The third is the one that finds it.';
  box.append(lead);
  const rows = [
    ['Narrative graph', 'reachability over the step graph — what a dead-end check does', r?.narrative, d => d?.detail, true],
    ['World facts', 'is there any ordering that completes every quest', r?.world, d => d?.detail, true],
    ['Order-dependent softlock', 'can ordinary play reach a state that blocks a quest forever', r?.softlock, d => d?.detail, false]
  ];
  rows.forEach(([name, what, d, meta, baseline]) => {
    const row = el('div', 'check' + (d && !d.ok ? ' is-fail' : '') + (baseline ? ' baseline' : ' headline'));
    row.append(Object.assign(el('span', 'g ' + (pending ? '' : d?.ok ? 'pass' : 'fail')), { textContent: pending ? '·' : d?.ok ? '✓' : '✗' }));
    const c = el('div');
    c.append(Object.assign(el('div', 'name'), { textContent: name }), Object.assign(el('div', 'what'), { textContent: what }));
    const mt = el('div', 'meta' + (pending ? ' sk' : ''));
    mt.textContent = pending ? 'checking…' : (meta(d) || '');
    c.append(mt); row.append(c); box.append(row);
  });

  const why = $('#why');
  const traps = r?.softlock?.traps || [];
  const chain = r?.world?.chain;
  if (!pending && (traps.length || chain)) {
    why.hidden = false; why.replaceChildren(el('h3', null, 'Why'));
    const ol = el('ol');
    if (chain) chain.forEach(l => {
      const li = el('li', l.severed ? 'sev' : null);
      li.style.paddingLeft = (l.depth * 14) + 'px';
      li.textContent = (l.severed ? '✗ ' : '└ ') + l.text; ol.append(li);
    });
    else traps.forEach(t => {
      const a = el('li'); a.textContent = `└ ${t.goalLabel} needs ${t.blocked.join(' and ')}`; ol.append(a);
      const b = el('li', 'sev'); b.style.paddingLeft = '14px';
      b.textContent = `✗ ${t.byLabel} consumes it, and a quest step cannot be repeated`; ol.append(b);
    });
    why.append(ol);
  } else why.hidden = true;

  if (!pending && r) {
    const bits = [`exit ${r.world.ok && r.softlock.ok ? 0 : 1}`];
    if (r.world.states) bits.push(`${r.world.states.toLocaleString()} states for reachability`);
    if (r.softlock.states) bits.push(`${r.softlock.states.toLocaleString()} for softlock`);
    if (r.ms) bits.push(`${r.ms} ms`);
    if (live) bits.push('run just now, in this browser');
    else if (cur.baked?.at) bits.push(`recorded run of ${cur.baked.at.slice(0, 16).replace('T', ' ')}`);
    if (pasted?.provider) bits.push(`typed by ${pasted.provider}/${pasted.model}`);
    $('#telemetry').innerHTML = bits.map(b => `<b>${esc(b)}</b>`).join(' · ');
  }
}

